// Builds src/pages/typescriptQuestionsData.js from questions.mjs.
// For every example: writes it to work/NN/, type-checks it with the local tsc
// (--noEmit --strict, target ES2022, lib dom), runs it with Node when it prints,
// checks the result matches its 'kind', and pastes the real output.
// Usage: node scripts/ts_questions/gen.mjs   (needs `npm i` in this folder)
import { execFileSync, spawnSync } from 'node:child_process'
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { questions } from './questions.mjs'

const here = new URL('.', import.meta.url).pathname
const work = join(here, 'work')
const tsc = join(here, 'node_modules', '.bin', 'tsc')
const out = join(here, '..', '..', 'src', 'pages', 'typescriptQuestionsData.js')

const BASE = ['--strict', '--target', 'es2022', '--lib', 'es2022,dom', '--module', 'nodenext',
  '--jsx', 'react-jsx', '--skipLibCheck', '--pretty', 'false']

rmSync(work, { recursive: true, force: true })
mkdirSync(work)
writeFileSync(join(work, 'package.json'), '{ "type": "module" }\n')

// Split '// file: name' sections; no marker means one main.ts / main.tsx.
function splitFiles(item) {
  const lines = item.code.split('\n')
  if (!lines[0].startsWith('// file: ')) return [[item.tsx ? 'main.tsx' : 'main.ts', item.code]]
  const files = []
  for (const line of lines) {
    if (line.startsWith('// file: ')) files.push([line.slice(9).trim(), []])
    else files.at(-1)[1].push(line)
  }
  return files.map(([name, body]) => [name, body.join('\n') + '\n'])
}

function run(cmd, args, cwd) {
  const r = spawnSync(cmd, args, { cwd, encoding: 'utf8' })
  return { code: r.status, stdout: r.stdout, stderr: r.stderr }
}

// "main.ts(4,3): error TS2322: msg" -> "error TS2322: msg"; keep indented detail lines.
function cleanErrors(text) {
  return text.trimEnd().split('\n').filter(Boolean)
    .map((l) => l.replace(/^\S+\(\d+,\d+\): /, '')).join('\n')
}

const problems = []
const results = questions.map((item, i) => {
  const dir = join(work, String(i + 1).padStart(2, '0'))
  mkdirSync(dir)
  const files = splitFiles(item)
  for (const [name, body] of files) writeFileSync(join(dir, name), body)
  const sources = files.map(([n]) => n).filter((n) => /\.tsx?$/.test(n))
  const main = sources.filter((n) => !n.endsWith('.d.ts')).at(-1)

  const check = item.project
    ? run(tsc, ['-p', '.', '--pretty', 'false'], dir)
    : run(tsc, ['--noEmit', '--allowImportingTsExtensions', ...BASE, ...(item.flags || []), ...sources], dir)
  const errors = cleanErrors(check.stdout + check.stderr)
  const wantErrors = item.kind !== 'prints'
  if (wantErrors && (check.code === 0 || !errors.includes('error TS')))
    problems.push(`Q${i + 1} expected type errors but tsc passed: ${item.q}`)
  if (!wantErrors && check.code !== 0) problems.push(`Q${i + 1} should type-check: ${item.q}\n${errors}`)

  let stdout = ''
  if (item.kind !== 'error') {
    let r
    if (item.run === 'tsc') {
      const emit = run(tsc, [...BASE, '--outDir', 'js', ...sources], dir)
      if (emit.code !== 0) problems.push(`Q${i + 1} tsc emit failed: ${emit.stdout}`)
      r = run('node', [join('js', main.replace(/\.tsx?$/, '.js'))], dir)
    } else {
      const extra = item.run === 'transform' ? ['--experimental-transform-types'] : []
      r = run('node', ['--no-warnings', ...extra, main], dir)
    }
    if (r.code !== 0) problems.push(`Q${i + 1} node exited ${r.code}: ${item.q}\n${r.stderr}`)
    stdout = r.stdout.trimEnd()
    if (!stdout) problems.push(`Q${i + 1} printed nothing: ${item.q}`)
  }

  const lines = item.code.split('\n').length
  if (lines > (item.level === 'Coding round' ? 15 : 13)) console.log(`  note: Q${i + 1} example has ${lines} lines`)

  const output = item.kind === 'error' ? errors
    : item.kind === 'prints' ? stdout
    : `${errors}\n\nIf you run the JavaScript anyway:\n${stdout}`
  return { q: item.q, level: item.level, a: item.a, code: item.code, output }
})

if (problems.length) {
  console.error(problems.join('\n\n'))
  process.exit(1)
}

const tpl = (s) => '`' + s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`'
const version = execFileSync(tsc, ['--version'], { encoding: 'utf8' }).trim()
const body = results.map((r) => `  {
    q: ${JSON.stringify(r.q)},
    level: '${r.level}',
    a: ${JSON.stringify(r.a)},
    code: ${tpl(r.code)},
    output: ${tpl(r.output)},
  },`).join('\n')

writeFileSync(out, `// TypeScript interview questions, basics to advanced.
// Each item: { q, level, a, code, output }. Generated by scripts/ts_questions/gen.mjs:
// type errors are real tsc output (${version}, --strict) and printed output is the
// real stdout from running the example with Node ${process.version}.

export const questions = [
${body}
]
`)
console.log(`wrote ${results.length} questions to ${out}`)
