// Builds src/pages/angularQuestionsData.js and src/pages/topics/angularTopics.js from questions.mjs.
// Items with `run` are real: the code is type-checked with tsc (--strict) and run with Node,
// and the printed output is pasted in (`ctx: true` runs the body inside an Angular injection
// context from env.ts, so effect()/toSignal()/resource()/inject() work). `kind: 'error'` items
// must fail type-checking and show the real tsc error. Other outputs are written by hand.
// Usage: node scripts/angular_questions/gen.mjs   (needs `npm i` in this folder)
import { spawnSync } from 'node:child_process'
import { mkdirSync, rmSync, writeFileSync, copyFileSync } from 'node:fs'
import { join } from 'node:path'
import { topics } from './questions.mjs'

const here = new URL('.', import.meta.url).pathname
const work = join(here, 'work')
const tsc = join(here, 'node_modules', '.bin', 'tsc')
const pages = join(here, '..', '..', 'src', 'pages')
const BASE = ['--strict', '--target', 'es2022', '--lib', 'es2022,dom', '--module', 'nodenext',
  '--experimentalDecorators', '--skipLibCheck', '--pretty', 'false']

rmSync(work, { recursive: true, force: true })
mkdirSync(work)
writeFileSync(join(work, 'package.json'), '{ "type": "module" }\n')
copyFileSync(join(here, 'env.ts'), join(work, 'env.ts'))

const run = (cmd, args, cwd) => {
  const r = spawnSync(cmd, args, { cwd, encoding: 'utf8', timeout: 30000 })
  return { code: r.status, stdout: r.stdout || '', stderr: r.stderr || '' }
}

function source(item) {
  // Load the JIT compiler first: Angular's npm packages are partially compiled.
  const code = "import '@angular/compiler'\n" + (typeof item.run === 'string' ? item.run : item.code)
  if (!item.ctx) return code
  const lines = code.split('\n')
  const imports = [], body = []
  let inImport = false
  for (const l of lines) {
    if (l.startsWith('import ') || inImport) { imports.push(l); inImport = !/from '[^']+'/.test(l) && !/^import '/.test(l) }
    else body.push(l)
  }
  return [...imports, "import { runInInjectionContext as __run } from '@angular/core'",
    "import { injector as __injector, settle as __settle } from './env.js'",
    'await __run(__injector, async () => {', ...body.map((l) => '  ' + l.replace(/^export /, '')), '})', 'await __settle()', ''].join('\n')
}

const problems = []
let n = 0
const all = []
for (const t of topics) for (const item of t.items) {
  n++
  if (!item.run && item.kind !== 'error') { all.push(item); continue }
  const dir = join(work, String(n).padStart(2, '0'))
  mkdirSync(dir)
  writeFileSync(join(dir, 'package.json'), '{ "type": "module" }\n')
  copyFileSync(join(here, 'env.ts'), join(dir, 'env.ts'))
  writeFileSync(join(dir, 'main.ts'), source(item))
  const check = run(tsc, [...BASE, 'main.ts', 'env.ts'], dir)
  const errors = (check.stdout + check.stderr).trim().split('\n').filter((l) => l.startsWith('main.ts'))
    .map((l) => l.replace(/^\S+\(\d+,\d+\): /, '')).join('\n')
  let output
  if (item.kind === 'error') {
    if (!errors) problems.push(`#${n} expected a type error: ${item.q}`)
    output = errors + (item.after ? '\n\n' + item.after : '')
  } else {
    if (check.code !== 0) { problems.push(`#${n} tsc failed: ${item.q}\n${check.stdout}${check.stderr}`); output = '' }
    else {
      const r = run('node', ['main.js'], dir)
      if (r.code !== 0) problems.push(`#${n} node failed: ${item.q}\n${r.stderr}`)
      output = r.stdout.trimEnd()
      if (!output) problems.push(`#${n} printed nothing: ${item.q}`)
    }
    if (item.before) output = item.before + '\n' + output
    if (item.after) output += '\n\n' + item.after
  }
  all.push({ ...item, output })
}

const lit = (s) => '`' + s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`'
const data = `// Angular interview questions, basics to advanced.
// Each item: { q, level, a, code, output }. Generated by scripts/angular_questions/gen.mjs.
// Outputs of runnable examples (signals, RxJS, DI, pipes' transform, forms models, HttpClient
// against jsonplaceholder) are the real stdout from Node v24 with @angular/core 22.2.4 and
// rxjs 7.8.2; rendered-template outputs are written by hand. The simple unit-test questions'
// outputs are real \`ng test\` (Vitest) runs from scripts/testing_questions/angular.

export const questions = [
${all.map((x) => `  {
    q: ${JSON.stringify(x.q)},
    level: '${x.level}',
    a: ${JSON.stringify(x.a)},
    code: ${lit(x.code)},
    output: ${lit(x.output)},
  },`).join('\n')}
]
`
const topicFile = `// Sub-topic order for the angular page: related questions are shown together.
// Each question title appears in exactly one topic, in the order shown on the page.
// Generated by scripts/angular_questions/gen.mjs.
export default [
${topics.map((t) => `  {
    topic: ${JSON.stringify(t.topic)},
    questions: [
${t.items.map((x) => `      ${JSON.stringify(x.q)},`).join('\n')}
    ],
  },`).join('\n')}
]
`
writeFileSync(join(pages, 'angularQuestionsData.js'), data)
writeFileSync(join(pages, 'topics', 'angularTopics.js'), topicFile)
const levels = {}
for (const x of all) levels[x.level] = (levels[x.level] || 0) + 1
console.log(all.length, 'questions', levels, `${all.filter((x) => x.run).length} run for real`)
for (const p of problems) console.log('PROBLEM', p)
process.exit(problems.length ? 1 : 0)
